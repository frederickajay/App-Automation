#!/usr/bin/env node
// Turns the platform-neutral strings into each platform's format, so both apps ship
// the same reviewed translations and you pay for the 18-language fan-out once.
//   node automation/tools/export-strings.mjs --ios path/to/Localizable.xcstrings
//   node automation/tools/export-strings.mjs --android path/to/app/src/main/res
// Placeholders: {0},{1}… become %1$@,%2$@… on iOS and %1$s,%2$s… on Android.
import fs from 'node:fs';
import path from 'node:path';
import { AUTOMATION_DIR, loadConfig, readJson } from '../lib/util.mjs';

const config = loadConfig();
const dir = path.join(AUTOMATION_DIR, 'l10n');
const source = readJson(path.join(dir, 'strings.source.json'));
const srcLang = config.app.sourceLanguage;
const langs = config.app.languages;
const tr = Object.fromEntries(langs.map((l) => [l, l === srcLang
  ? Object.fromEntries(Object.entries(source).map(([k, v]) => [k, v.value]))
  : readJson(path.join(dir, 'translations', `${l}.json`), {})]));

const args = process.argv.slice(2);
const opt = (name) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : null; };
const iosOut = opt('--ios');
const androidOut = opt('--android');
if (!iosOut && !androidOut) { console.error('Usage: --ios <file.xcstrings> and/or --android <res dir>'); process.exit(1); }

const toIos = (s) => s.replace(/\{(\d+)\}/g, (_, n) => `%${Number(n) + 1}$@`);
const toAndroid = (s) => s.replace(/\{(\d+)\}/g, (_, n) => `%${Number(n) + 1}$s`);

if (iosOut) {
  const out = { sourceLanguage: srcLang, strings: {}, version: '1.0' };
  for (const [key, src] of Object.entries(source)) {
    const entry = { localizations: {} };
    if (src.comment) entry.comment = src.comment;
    for (const l of langs) {
      const v = tr[l][key];
      if (typeof v === 'string' && v) entry.localizations[l] = { stringUnit: { state: 'translated', value: toIos(v) } };
    }
    out.strings[key] = entry;
  }
  fs.mkdirSync(path.dirname(path.resolve(iosOut)), { recursive: true });
  fs.writeFileSync(iosOut, JSON.stringify(out, null, 2) + '\n');
  console.log(`Wrote ${iosOut} (${Object.keys(source).length} keys × ${langs.length} languages)`);
}

// Android resource qualifiers: pt-BR -> values-pt-rBR, zh-Hans -> values-b+zh+Hans
function androidFolder(lang) {
  if (lang === srcLang) return 'values';
  const parts = lang.split('-');
  if (parts.length === 1) return `values-${lang}`;
  if (parts.length === 2 && /^([A-Z]{2}|\d{3})$/.test(parts[1])) return `values-${parts[0]}-r${parts[1]}`;
  return `values-b+${parts.join('+')}`;
}
const xmlEsc = (s) => toAndroid(s)
  .replace(/\\/g, '\\\\').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/^([@?])/, '\\$1');
const androidName = (key) => key.replace(/[^A-Za-z0-9_]/g, '_');

if (androidOut) {
  for (const l of langs) {
    const lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by automation/tools/export-strings.mjs. Edit automation/l10n instead. -->', '<resources>'];
    for (const [key, src] of Object.entries(source)) {
      const v = tr[l][key];
      if (typeof v !== 'string' || !v) continue;
      if (l === srcLang && src.comment) lines.push(`    <!-- ${src.comment.replace(/--/g, '-')} -->`);
      const formatted = /\{\d+\}/.test(v) ? '' : ' formatted="false"';
      lines.push(`    <string name="${androidName(key)}"${/%/.test(v) && formatted ? formatted : ''}>${xmlEsc(v)}</string>`);
    }
    lines.push('</resources>', '');
    const folder = path.join(androidOut, androidFolder(l));
    fs.mkdirSync(folder, { recursive: true });
    fs.writeFileSync(path.join(folder, 'strings.xml'), lines.join('\n'));
  }
  console.log(`Wrote strings.xml for ${langs.length} languages under ${androidOut}`);
}
